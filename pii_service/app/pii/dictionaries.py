_WS = re.compile(r"[\s,.]+")
_STREET_MARKERS = re.compile(r"(?i)\b(?:г|город|ул|улица|д|дом|пр|проспект|москва|санкт-петербург)\b\.?")


def normalize_phone(text: str) -> str:
    digits = "".join(ch for ch in text if ch.isdigit())
    if len(digits) == 11 and digits[0] == "8":
        digits = "7" + digits[1:]
    elif len(digits) == 10:
        digits = "7" + digits
    return digits


def is_official_phone(text: str) -> bool:
    d = normalize_phone(text)
    return d in OFFICIAL_PHONES or d.startswith(ORG_PHONE_PREFIXES)


def is_org_email(text: str) -> bool:
    local = text.split("@", 1)[0].lower()
    base = re.split(r"[+.\-_]", local, 1)[0]
    return local in ORG_EMAIL_LOCALPARTS or base in ORG_EMAIL_LOCALPARTS


def is_branch_address(text: str) -> bool:
    norm = _WS.sub(" ", _STREET_MARKERS.sub(" ", text.lower())).strip()
    padded = f" {norm} "
    return any(f" {b} " in padded for b in BRANCH_ADDRESSES)
