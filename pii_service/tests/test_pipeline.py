@pytest.mark.parametrize("text,fragment", MUST_MASK)
def test_must_mask(text, fragment):
    out = masked(text)
    assert fragment not in out, out


@pytest.mark.parametrize("text", MUST_KEEP)
def test_must_keep(text):
    assert masked(text) == text


def test_client_vs_branch_same_address_in_one_text():
    text = "Адрес отделения банка: Москва, Тверская 10. Адрес клиента: Москва, Тверская 10"
    out = masked(text)
    assert out.startswith("Адрес отделения банка: Москва, Тверская 10.")
    assert out.endswith("Адрес клиента: ******, ******** **")


def test_mixed_org_and_personal_contacts():
    out = masked("Звоните в офис +7 495 123-45-67, клиент Сидоров, моб. +7 916 111-22-33")
    assert "+7 495 123-45-67" in out
    assert "111-22" not in out and "Сидоров" not in out
    out = masked("Пишите на info@bank.ru или клиенту на petrov.i@mail.ru")
    assert "info@bank.ru" in out and "petrov.i" not in out


def test_pin_needs_card_context():
    assert "1234" in masked("Введите код 1234")
    assert "4567" not in masked("Карта 4276 1234 5678 9012, CVV 123, PIN 4567")


def test_bare_numbers_not_cvv_pin_passport():
    text = "Позиция 123, количество 1234, номер 4506123456"
    assert masked(text) == text


def test_structured_json_uses_field_names():
    text = ('{"customer_name": "Сидоров Пётр Петрович", "office_phone": "8 800 555 35 35", '
            '"delivery_date": "12.03.2025", "birth_date": "01.02.1980", '
            '"client_address": "Москва, ул. Лесная, д. 12, кв. 34", "support_email": "help@bank.ru"}')
    out = masked(text)
    assert "Сидоров" not in out
    assert "8 800 555 35 35" in out
    assert "12.03.2025" in out
    assert "01.02" not in out
    assert "Лесная" not in out
    assert "help@bank.ru" in out


def test_query_string_and_logs():
    out = masked("GET /v1/clients?client_phone=%2B79161234567&client_email=petr%40mail.ru&id=4506123456")
    assert "9161234" not in out and "petr%40" not in out and "id=4506123456" in out
    out = masked("2024-01-01 12:00:00 INFO login customer_phone=+79161234567 email=petr@mail.ru order_id=4506123456")
    assert "9161234" not in out and "petr@" not in out and "order_id=4506123456" in out


def test_full_client_card():
    text = ("Романов Илья Сергеевич, дата рождения 16 января 1991 года, паспорт 4014 582731, "
            "код подразделения 780-117, телефон +7 921 448-17-63, email ilya.romanov@pochta.example, "
            "адрес Санкт-Петербург, улица Марата, дом 36, квартира 58, карта 4556 7301 2345 6789, "
            "имя держателя ИЛЬЯ РОМАНОВ, защитный код карты 903, код доступа к карте 4412")
    out, types, _ = mask_text(text)
    for frag in ("Романов", "16 января", "582731", "780-117", "448-17", "ilya.romanov", "Марата",
                 "7301 2345", "ИЛЬЯ", "903", "4412"):
        assert frag not in out, frag
    assert {"FIO", "DATE_TEXT", "PASSPORT", "DEPT_CODE", "PHONE", "EMAIL", "ADDRESS", "CARD",
            "CARDHOLDER", "CVV", "PIN"} <= set(types)


def test_enabled_types_gate():
    out, types, _ = mask_text("Иванов Иван Иванович, тел +7 912 345 67 89", ["PHONE"])
    assert "Иванов" in out and "345" not in out and types == ["PHONE"]


def test_format_mode_fully_masks_span_content():
    out = masked("Иван Петрович Сидоров, email ivan@example.com, тел +7 912 345 67 89")
    assert out == "**** ******** *******, email ****@*******.***, тел +* *** *** ** **"
    assert masked("Дата рождения 12.03.1990") == "Дата рождения **.**.****"
    assert masked("Карта 4276 1234 5678 9012") == "Карта **** **** **** ****"
    assert "1990" not in out and "912" not in out and "ivan" not in out.lower()


def test_idempotent_remask():
    text = "Клиент Иванов Иван Иванович, тел +7 912 345 67 89, адрес: г. Москва, ул. Лесная, д. 12, кв. 3"
    once = masked(text)
    assert masked(once) == once
